// جدولٌ مبنيٌّ مرّةً: صورةُ اللفظ المجرَّدة ← أسماءُ حقوله
const WORD_FIELDS = new Map();
for (const [field, words] of Object.entries(MEANING_FIELDS)) {
  for (const w of words) {
    for (const form of new Set([normalize(w), bareForm(normalize(w))])) {
      if (!form) continue;
      if (!WORD_FIELDS.has(form)) WORD_FIELDS.set(form, new Set());
      WORD_FIELDS.get(form).add(field);
    }
  }
}

/** حقولُ المعنى التي وقع في النصّ لفظٌ منها. */
export function fieldsOf(text) {
  const found = new Map();      // اسمُ الحقل ← عددُ ألفاظه في النصّ
  for (const w of normalize(text).split(' ').filter(Boolean)) {
    for (const form of new Set([w, bareForm(w)])) {
      for (const field of WORD_FIELDS.get(form) ?? []) {
        found.set(field, (found.get(field) ?? 0) + 1);
      }
    }
  }
  return [...found.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([field, hits]) => ({ field, hits }));
}

const MAX_FIELDS = 2;
const MAX_TERMS = 10;

/**
 * ★ توسيعُ السؤال بإخوة ألفاظه في المعنى. ★
 * يُرجع [{ field, terms }] — وألفاظُ السؤال نفسُها محذوفةٌ منها (فقد بُحث بها).
 */
export function expandByMeaning(text, { maxFields = MAX_FIELDS, maxTerms = MAX_TERMS } = {}) {
  const have = new Set(normalize(text).split(' ').filter(Boolean).flatMap((w) => [w, bareForm(w)]));
  const out = [];
  for (const { field } of fieldsOf(text).slice(0, maxFields)) {
    const terms = MEANING_FIELDS[field]
      .map((w) => normalize(w))
      .filter((w) => w && !have.has(w) && !have.has(bareForm(w)))
      .slice(0, maxTerms);
    if (terms.length) out.push({ field, terms });
  }
  return out;
}
